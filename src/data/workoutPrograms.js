// Библиотека — это не замена персонального плана. Эти правила лишь помогают
// показать пользователю подходящие готовые варианты и не выдавать интенсивные
// форматы как первую рекомендацию при отмеченных ограничениях.
const LEVEL_RANK = { beginner: 1, amateur: 2, advanced: 3, professional: 4 }
const PROGRAM_LEVEL_RANK = { 'Новичок': 1, 'Средний': 2, 'Продвинутый': 3 }
const HIGH_INTENSITY_PROGRAMS = new Set([
  'sprint-intervals', 'tabata-20-10', 'hiit-20min', 'functional-circuit',
  'bike-intervals', 'rowing-intervals', 'jump-rope-cardio', 'emom', 'amrap',
  'kettlebell-complex', 'crossfit-wod',
])

const GOAL_CATEGORIES = {
  weight_loss: new Set(['cardio', 'circuit', 'strength', 'home', 'mobility']),
  muscle_gain: new Set(['strength', 'focus', 'home']),
  strength: new Set(['strength', 'focus']),
  endurance: new Set(['cardio', 'circuit']),
  health: new Set(['strength', 'cardio', 'mobility', 'home']),
  maintenance: new Set(['strength', 'cardio', 'mobility', 'home']),
}

export function getProgramFit(program, profile = {}) {
  const userRank = LEVEL_RANK[profile.level] || LEVEL_RANK.amateur
  const programRank = PROGRAM_LEVEL_RANK[program.level] || 2
  const goals = Array.isArray(profile.goals) && profile.goals.length ? profile.goals : ['health']
  const matchesGoal = goals.some(goal => GOAL_CATEGORIES[goal]?.has(program.category))
  const hasLimitations = Boolean(profile.hasLimitations || profile.limitationsText || profile.aiAnalysis)
  const isHighIntensity = HIGH_INTENSITY_PROGRAMS.has(program.id)

  if (hasLimitations && isHighIntensity) {
    return { recommended: false, reason: 'Высокая интенсивность: сначала согласуйте нагрузку со специалистом.' }
  }
  if (programRank > userRank) {
    return { recommended: false, reason: `Требуется уровень: ${program.level.toLowerCase()}.` }
  }
  if (!matchesGoal) return { recommended: false, reason: 'Не в приоритете для выбранной цели.' }
  return { recommended: true, reason: 'Соответствует вашему уровню и цели.' }
}

