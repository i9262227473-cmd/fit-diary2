// Короткий помощник для описания упражнения программы. targetReps может быть
// как диапазоном повторов ('8-12'), так и временем ('40 сек') — оба формата
// уже используются в приложении (например, для планки).
function ex(name, muscle, sets, targetReps = '8-12', restSec = 90, type = 'compound') {
  return {
    name,
    muscle,
    type,
    targetReps,
    restSec,
    sets: Array.from({ length: sets }, () => ({ reps: targetReps, weight: '0' })),
  }
}

