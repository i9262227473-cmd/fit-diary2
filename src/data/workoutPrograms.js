export function getCuratedProgramFit(program, profile = {}) {
  const userRank = LEVEL_RANK[profile.level] || LEVEL_RANK.amateur
  const programRank = PROGRAM_LEVEL_RANK[program.level] || 2
  const hasLimitations = Boolean(profile.hasLimitations || profile.limitationsText || profile.aiAnalysis)
  const goals = Array.isArray(profile.goals) && profile.goals.length ? profile.goals : ['health']
  const goalMatch = program.category === 'lower-focus'
    ? goals.some(goal => ['muscle_gain', 'maintenance', 'health'].includes(goal))
    : goals.some(goal => GOAL_CATEGORIES[goal]?.has(program.category === 'fullbody' ? 'strength' : 'strength'))
  if (programRank > userRank) return { recommended: false, reason: `Требуется уровень: ${program.level.toLowerCase()}.` }
  if (hasLimitations && program.level === 'Продвинутый') return { recommended: false, reason: 'При ограничениях сначала нужен персональный AI-план.' }
  if (!goalMatch) return { recommended: false, reason: 'Не в приоритете для выбранной цели.' }
  return { recommended: true, reason: 'Соответствует вашему уровню и цели.' }
}
